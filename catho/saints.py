def saints_du_jour(mois: int, jour: int) -> list[dict]:
    return [s for s in SAINTS if s["fete"] == (mois, jour)]


def prochain_saint(mois: int, jour: int) -> dict:
    """Premier saint dont la fête est le jour donné ou après (en bouclant sur l'année)."""
    suivants = sorted(SAINTS, key=lambda s: s["fete"])
    for s in suivants:
        if s["fete"] >= (mois, jour):
            return s
    return suivants[0]
